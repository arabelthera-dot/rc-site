function addMsg(text,who){
  var d=document.createElement('div'); d.className='msg '+who; d.textContent=text;
  document.getElementById('chatBox').appendChild(d);
  d.scrollIntoView({behavior:'smooth',block:'nearest'});
}
function findAnswer(q){
  q=q.toLowerCase();
  for (var i=0;i<kb.length;i++){ if (kb[i].k.some(function(k){return q.indexOf(k)>=0;})) return kb[i].a; }
  return 'Спросите точнее — о движении энергии, о защите диссертации, о Пойнтинге, о задаче Кирхгофа или о моих опытах на лекциях. Отвечу как было.';
}
function sendChat(){
  var inp=document.getElementById('chatInput'), q=inp.value.trim();
  if (!q) return;
  addMsg(q,'you'); inp.value='';
  setTimeout(function(){ addMsg(findAnswer(q),'inv'); award('chat',5); },600);
}
document.getElementById('chatSend').onclick=sendChat;
document.getElementById('chatInput').addEventListener('keydown',function(e){ if(e.key==='Enter') sendChat(); });
