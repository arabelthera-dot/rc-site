// Сценарий прохода: 29 января, Костович «Держи форму на ветру» (нестандартная игра: кнопки «держи» без data-igra-hod).
// Как играет ребёнок: держит «Ветер», пока мягкий баллон не сомнётся → «Вставить каркас» → 4 мигающие детали
// по порядку → снова держит «Ветер» → держит «Тянуть», пока корпус не станет 64 м → финал.
export const final = '.ko-finale';

export default async function (i) {
  await i.derzhi('.ko-wind', { poka: '.ko-next', ms: 12_000, opis: 'держать «Ветер», пока баллон не сомнётся' });
  await i.tap('.ko-next', 'тап «Вставить каркас Костовича»');
  for (let k = 1; k <= 4; k++) await i.tap('.ko-part.next', `тап мигающей детали ${k} из 4`);
  await i.derzhi('.ko-wind', { poka: '.ko-stretch', ms: 12_000, opis: 'держать «Ветер» на каркас' });
  await i.derzhi('.ko-stretch', { poka: '.ko-finale', ms: 12_000, opis: 'держать «Тянуть» до 64 м' });
}
